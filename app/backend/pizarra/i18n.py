def set_language(language):
    global _language
    _language = language if language in CATALOGS else "es"


def language():
    """El idioma de la app ahora (`es` o `en`)."""
    return _language


class _Keep(dict):
    def __missing__(self, key):
        return "{" + key + "}"


def t(key, language=None, **vars):
    text = CATALOGS.get(language or _language, ES).get(key)
    if text is None:
        log.warning("[i18n] falta la clave %s", key)
        return key
    return text.format_map(_Keep(vars)) if vars else text.replace("{{", "{").replace("}}", "}")
